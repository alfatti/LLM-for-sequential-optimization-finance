#!/usr/bin/env python3
"""Unified evaluation harness (GPU) for Q1 / Q2 / Q4 bundles.

Protocol (paper-faithful): outputs are restricted to the action grid; at each
decision the model scores every candidate action string and the argmax is
executed (greedy). Rollouts are CLOSED-LOOP: the query path is generated by the
model's own actions under CRN Brownian increments fixed per bundle row
(policy-independent, so all arms face identical shocks).

Scoring modes:
  cached (default): one forward over the prefix builds a KV cache; candidates
      are scored in chunks against the repeated cache. Fast; exact up to
      tokenizer boundary merges at the 'a='|candidate seam, which are spot-
      checked against the exact scorer at startup (--verify-naive).
  naive: exact full-sequence log-probability per candidate (slow; ground truth).

Arms:
  --adapter <dir>   SFT arm (Q1 or Q4 checkpoints)
  (no adapter)      ICL-only / zero-shot base-model arm (Q2; baselines)

Examples:
  python scripts/eval_llm.py --data data_main --bundle q4/eval_bundle.jsonl \
      --adapter runs/q4_n3200/adapter_final --arm sft_n3200 --out results/q4_sft_n3200
  python scripts/eval_llm.py --data data_main --bundle q2/eval_bundle.jsonl \
      --arm icl_base --out results/q2_icl
  python scripts/eval_llm.py --data data_main --bundle q1/eval_bundle.jsonl \
      --adapter runs/q1/adapter_final --arm q1_sft --out results/q1_sft \
      --probe-bundle q1/probe_bundle.jsonl
"""
import argparse
import json
import os
import sys
from typing import List, Optional

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

from merton_meta.config import ExperimentConfig  # noqa: E402
from merton_meta.datagen import query_z  # noqa: E402
from merton_meta.env import log_ce_gap, pistar_to_mu, step_log_wealth  # noqa: E402
from merton_meta.metrics import dump_json, load_jsonl, summarize_results  # noqa: E402
from merton_meta.serialize import fmt_action, render_decision_prompt  # noqa: E402


def build_grid(cfg: ExperimentConfig) -> List[float]:
    g = cfg.grid
    n = int(round((g.hi - g.lo) / g.step)) + 1
    return [float(f"{g.lo + i * g.step:+.2f}") for i in range(n)]


class CandidateScorer:
    def __init__(self, model, tok, cand_strings: List[str], device,
                 mode: str = "cached", chunk: int = 24):
        import torch
        self.torch = torch
        self.model, self.tok, self.device = model, tok, device
        self.mode, self.chunk = mode, chunk
        self.cands = cand_strings
        ids = [tok(c, add_special_tokens=False)["input_ids"] for c in cand_strings]
        self.cand_ids = ids
        self.by_len = {}
        for i, seq in enumerate(ids):
            self.by_len.setdefault(len(seq), []).append(i)

    # ---------------- exact (naive) ----------------
    def score_naive(self, prefix: str) -> np.ndarray:
        torch = self.torch
        scores = np.full(len(self.cands), -np.inf)
        texts = [prefix + c for c in self.cands]
        bs = self.chunk
        with torch.no_grad():
            for s in range(0, len(texts), bs):
                batch = texts[s:s + bs]
                enc = self.tok(batch, return_tensors="pt", padding=True,
                               add_special_tokens=True).to(self.device)
                out = self.model(**enc)
                logp = torch.log_softmax(out.logits.float(), dim=-1)
                ids = enc["input_ids"]
                mask = enc["attention_mask"]
                tgt = logp[:, :-1, :].gather(-1, ids[:, 1:, None]).squeeze(-1)
                tgt = tgt * mask[:, 1:]
                for j in range(len(batch)):
                    scores[s + j] = float(tgt[j].sum())
        return scores

    # ---------------- cached ----------------
    def _legacy_cache(self, pkv):
        if hasattr(pkv, "to_legacy_cache"):
            return pkv.to_legacy_cache()
        return pkv

    def _repeat_cache(self, legacy, b: int):
        return tuple(tuple(t.repeat(b, 1, 1, 1) for t in layer) for layer in legacy)

    def score_cached(self, prefix: str) -> np.ndarray:
        torch = self.torch
        enc = self.tok(prefix, return_tensors="pt",
                       add_special_tokens=True).to(self.device)
        plen = enc["input_ids"].shape[1]
        with torch.no_grad():
            out = self.model(**enc, use_cache=True)
        last_logp = torch.log_softmax(out.logits[0, -1].float(), dim=-1)
        legacy = self._legacy_cache(out.past_key_values)
        scores = np.full(len(self.cands), -np.inf)
        with torch.no_grad():
            for clen, idxs in self.by_len.items():
                for s in range(0, len(idxs), self.chunk):
                    sub = idxs[s:s + self.chunk]
                    b = len(sub)
                    cand = torch.tensor([self.cand_ids[i] for i in sub],
                                        device=self.device)
                    first = last_logp[cand[:, 0]]
                    if clen == 1:
                        for j, i in enumerate(sub):
                            scores[i] = float(first[j])
                        continue
                    pkv = self._repeat_cache(legacy, b)
                    try:
                        from transformers import DynamicCache
                        pkv_in = DynamicCache.from_legacy_cache(pkv)
                    except Exception:
                        pkv_in = pkv
                    attn = torch.ones((b, plen + clen), device=self.device,
                                      dtype=torch.long)
                    pos = torch.arange(plen, plen + clen,
                                       device=self.device).expand(b, clen)
                    o = self.model(input_ids=cand, attention_mask=attn,
                                   position_ids=pos, past_key_values=pkv_in,
                                   use_cache=True)
                    logp = torch.log_softmax(o.logits.float(), dim=-1)
                    rest = logp[:, :-1, :].gather(
                        -1, cand[:, 1:, None]).squeeze(-1).sum(dim=1)
                    tot = first + rest
                    for j, i in enumerate(sub):
                        scores[i] = float(tot[j])
        return scores

    def argmax_action(self, prefix: str, grid: List[float]) -> float:
        sc = (self.score_cached(prefix) if self.mode == "cached"
              else self.score_naive(prefix))
        return grid[int(np.argmax(sc))]


def load_model(model_name: str, adapter: Optional[str]):
    import torch
    from transformers import (AutoModelForCausalLM, AutoTokenizer,
                              BitsAndBytesConfig)
    tok = AutoTokenizer.from_pretrained(adapter or model_name, use_fast=True)
    if tok.pad_token is None:
        tok.pad_token = tok.eos_token
    tok.padding_side = "right"
    bnb = BitsAndBytesConfig(load_in_4bit=True, bnb_4bit_quant_type="nf4",
                             bnb_4bit_use_double_quant=True,
                             bnb_4bit_compute_dtype=torch.bfloat16)
    model = AutoModelForCausalLM.from_pretrained(
        model_name, quantization_config=bnb, torch_dtype=torch.bfloat16,
        device_map="auto")
    if adapter:
        from peft import PeftModel
        model = PeftModel.from_pretrained(model, adapter)
    model.eval()
    return model, tok


def rollout_row(row: dict, cfg: ExperimentConfig, scorer: CandidateScorer,
                grid: List[float]) -> dict:
    m = cfg.market
    mu = pistar_to_mu(row["pistar"], m)
    z = query_z(cfg, row["query_seed_tag"])
    xs, acts = [0.0], []
    for t in range(1, m.n_steps + 1):
        prompt = render_decision_prompt(row["demos_text"], xs[:-1], acts,
                                        next_x=xs[-1], next_t=t,
                                        header=row.get("header", ""))
        a = scorer.argmax_action(prompt, grid)
        acts.append(a)
        xs.append(float(step_log_wealth(np.float64(xs[-1]), a, z[t - 1], mu, m)))
    return {**{k: row[k] for k in ("row_id", "exp", "tier", "task_id", "pistar",
                                   "ktest", "draw", "bayes_mean", "sample_mean")},
            "pi_hat": float(np.mean(acts)), "actions": acts,
            "log_ce_gap": log_ce_gap(acts, row["pistar"], m)}


def run_probe(rows: List[dict], scorer: CandidateScorer, grid: List[float]) -> List[dict]:
    from merton_meta.serialize import DECISION_PREFIX, fmt_state
    out = []
    for r in rows:
        acts = []
        for x in r["x_values"]:
            open_line = (f"t={r['t_probe']:02d} x={fmt_state(x)} "
                         f"{DECISION_PREFIX}")
            a = scorer.argmax_action(r["history_text"] + "\n" + open_line, grid)
            acts.append(a)
        acts = np.array(acts)
        out.append({"row_id": r["row_id"], "exp": "q1_probe",
                    "pistar": r["pistar"], "x_values": r["x_values"],
                    "actions_by_x": acts.tolist(),
                    "spread_max_minus_min": float(acts.max() - acts.min()),
                    "spread_std": float(acts.std())})
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", required=True, help="dir from make_data.py")
    ap.add_argument("--bundle", required=True, help="bundle path relative to --data")
    ap.add_argument("--probe-bundle", default=None)
    ap.add_argument("--model-name", default="meta-llama/Meta-Llama-3-8B")
    ap.add_argument("--adapter", default=None)
    ap.add_argument("--arm", required=True, help="arm label recorded in results")
    ap.add_argument("--out", required=True, help="output dir")
    ap.add_argument("--scoring", choices=["cached", "naive"], default="cached")
    ap.add_argument("--chunk", type=int, default=24)
    ap.add_argument("--verify-naive", type=int, default=8,
                    help="startup spot-check: #decisions compared cached vs naive")
    ap.add_argument("--limit", type=int, default=None)
    ap.add_argument("--tier", default=None, help="comma filter on tiers")
    ap.add_argument("--ktest", default=None, help="comma filter on ktest values")
    args = ap.parse_args()

    cfg = ExperimentConfig.from_json(os.path.join(args.data, "config.json"))
    grid = build_grid(cfg)
    rows = load_jsonl(os.path.join(args.data, args.bundle))
    if args.tier:
        keep = set(args.tier.split(","))
        rows = [r for r in rows if r["tier"] in keep]
    if args.ktest:
        keep_k = {int(k) for k in args.ktest.split(",")}
        rows = [r for r in rows if int(r["ktest"]) in keep_k]
    if args.limit:
        rows = rows[: args.limit]
    os.makedirs(args.out, exist_ok=True)

    model, tok = load_model(args.model_name, args.adapter)
    device = next(model.parameters()).device
    scorer = CandidateScorer(model, tok, [fmt_action(g) for g in grid], device,
                             mode=args.scoring, chunk=args.chunk)

    if args.scoring == "cached" and args.verify_naive > 0 and rows:
        rng = np.random.default_rng(0)
        agree = 0
        for _ in range(args.verify_naive):
            r = rows[int(rng.integers(len(rows)))]
            prompt = render_decision_prompt(r["demos_text"], [], [], 0.0, 1,
                                            header=r.get("header", ""))
            a1 = grid[int(np.argmax(scorer.score_cached(prompt)))]
            a2 = grid[int(np.argmax(scorer.score_naive(prompt)))]
            agree += int(abs(a1 - a2) < 1e-9)
        print(f"[eval] cached-vs-naive argmax agreement: {agree}/{args.verify_naive}")
        if agree < args.verify_naive:
            print("[eval] WARNING: disagreement detected; consider --scoring naive")

    results = []
    res_path = os.path.join(args.out, "results.jsonl")
    with open(res_path, "w") as f:
        for i, row in enumerate(rows):
            res = rollout_row(row, cfg, scorer, grid)
            res["arm"] = args.arm
            results.append(res)
            f.write(json.dumps(res) + "\n")
            if (i + 1) % 10 == 0:
                print(f"[eval] {i + 1}/{len(rows)} rows")

    m = cfg.market
    summary = summarize_results(results, cfg.grid.lo, cfg.grid.hi,
                                m.gamma, m.sigma, m.dt, m.n_steps)
    summary["arm"] = args.arm

    if args.probe_bundle:
        probe_rows = load_jsonl(os.path.join(args.data, args.probe_bundle))
        probe_res = run_probe(probe_rows, scorer, grid)
        with open(os.path.join(args.out, "probe_results.jsonl"), "w") as f:
            for r in probe_res:
                f.write(json.dumps(r) + "\n")
        summary["probe"] = {
            "mean_spread_max_minus_min": float(np.mean(
                [r["spread_max_minus_min"] for r in probe_res])),
            "mean_spread_std": float(np.mean(
                [r["spread_std"] for r in probe_res])),
            "n_histories": len(probe_res)}

    dump_json(summary, os.path.join(args.out, "summary.json"))
    print(f"[eval] wrote {res_path} and summary.json (arm={args.arm})")


if __name__ == "__main__":
    main()
